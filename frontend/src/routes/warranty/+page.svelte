	<h1>Warranty</h1>

	<p>
		Every piece we sell is covered by a 5-year structural warranty against defects in materials
		and joinery under normal household use &mdash; our way of standing behind the "no shortcuts"
		promise.
	</p>

	<h2>What's Covered</h2>
	<ul>
		<li>Joint failure (loose, cracked, or separated joinery)</li>
		<li>Structural frame defects</li>
		<li>Hardware failure under normal use</li>
	</ul>

	<h2>What's Not Covered</h2>
	<ul>
		<li>Normal wood movement, grain variation, or finish aging &mdash; expected characteristics of
			solid wood, not defects</li>
		<li>Damage from misuse, water exposure, or moving/shipping after original delivery</li>
		<li>Upholstery fabric wear (covered separately by the fabric manufacturer where applicable)</li>
	</ul>

	<h2>Making a Claim</h2>
	<p>
		<a href="/contact">Contact us</a> with your order details and photos of the issue. We'll repair,
		replace the affected part, or replace the piece, whichever makes the most sense.
	</p>
