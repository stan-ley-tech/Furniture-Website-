	<h1>Wood We Can Stand Behind</h1>
	<p>
		Building furniture that lasts for decades is, on its own, one of the most sustainable choices
		a furniture company can make &mdash; every piece we sell is one less piece heading to a
		landfill in five years. But we also care about where the wood comes from in the first place.
	</p>
	<h2>Responsibly Sourced Hardwood</h2>
	<p>
		We work with woodworkers who source from managed forests and reclaimed timber, avoiding
		old-growth and endangered species. We ask every workshop we partner with to share where their
		lumber comes from before we agree to sell their work.
	</p>
	<h2>Low-Waste Small Batches</h2>
	<p>
		We don't hold speculative inventory. Pieces are built in small runs against real demand, which
		keeps offcuts, overproduction, and warehoused unsold stock to a minimum.
	</p>
	<h2>Built to Be Repaired</h2>
	<p>
		Solid wood and mechanical joinery mean our furniture can be sanded, refinished, and repaired
		instead of replaced &mdash; the single biggest lever we have on long-term waste.
	</p>
